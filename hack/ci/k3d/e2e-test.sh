#!/usr/bin/env bash

# Description: This script runs given e2e tests on a k3d cluster.
# It deploys the operator image configured in the IMG variable and then runs the given make target
# It requires the following env variables:
# - IMG - An operator image to be deployed (by make deploy)
# - K3D_CONFIGURATION - configuration preset, used to load configurations/${K3D_CONFIGURATION}/vars.sh
# Optional env variables:
# - DEPLOY_RESTARTER - when "true", deploy the restarter E2E topology instead of the
#   default module: the base controller with --enable-restart=false (config/e2e-restarter
#   overlay) plus the standalone restarter controller (restarter/config/e2e overlay).
#   Requires RESTARTER_IMG to be set.
# - RESTARTER_IMG - restarter image deployed when DEPLOY_RESTARTER=true.

set -eo pipefail
script_dir="$(dirname "$(readlink -f "$0")")"
repo_root="$(cd "${script_dir}/../../.." && pwd)"
# shellcheck source=../common.sh
source "${script_dir}/../common.sh"

require_positional make_target "$1"

require_vars K3D_CONFIGURATION IMG

load_configuration "${K3D_CONFIGURATION}"

export IS_GARDENER=false

# Add pwd to path to be able to use binaries downloaded in scripts
export PATH="${PATH}:${PWD}"

start_group "Creating kyma-system namespace"
make create-namespace
end_group

start_group "Creating kyma-provisioning-info configmap"
make create-provisioning-info DUAL_STACK_ENABLED=false
end_group

if [ "${DEPLOY_RESTARTER}" = "true" ]; then
  require_vars RESTARTER_IMG

  start_group "Deploying base controller (--enable-restart=false), image: ${IMG}"
  # config/e2e-restarter references config/default, whose kustomization.yaml is
  # generated by `make module-version`.
  make module-version
  (cd "${repo_root}/config/manager" && kustomize edit set image "controller=${IMG}")
  kustomize build "${repo_root}/config/e2e-restarter" | kubectl apply -f -
  end_group

  start_group "Deploying restarter controller, image: ${RESTARTER_IMG}"
  (cd "${repo_root}/restarter/config/manager" && kustomize edit set image "controller=${RESTARTER_IMG}")
  kustomize build --load-restrictor LoadRestrictionsNone "${repo_root}/restarter/config/e2e" | kubectl apply -f -
  end_group

  start_group "Waiting for controllers to become available"
  kubectl rollout status -n kyma-system deployment/istio-controller-manager --timeout=300s
  kubectl rollout status -n restarter-system deployment/restarter-controller-manager --timeout=300s
  end_group
else
  start_group "Deploying module, image: ${IMG}"
  make deploy
  end_group
fi

start_group "Executing tests: ${make_target}"
make "${make_target}"
end_group
